// Helper calculations
export function calculatePiecePrice(pricePerKg, weightPerNotebookG) {
  return ((pricePerKg * weightPerNotebookG) / 1000);
}

export function formatGrams(grams) {
  if (grams >= 1000) {
    return `${(grams / 1000).toFixed(2)} KG`;
  }
  return `${Math.round(grams)}g`;
}
